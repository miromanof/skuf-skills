const distractorOffsets = [5, 13, 23] as const;

function displayedTerm(title: string): string {
  return title.split('/')[0]!.trim();
}

function option(term: string, situation: string): string {
  return `Фраза «${term}» появилась ${situation}.`;
}

function rotate<T>(items: T[], amount: number): T[] {
  return items.map((_, index) => items[(index + amount) % items.length]!);
}

export const mediumQuestions: QuizQuestion[] = dictionaryCards.map((card, index, cards) => {
  const term = displayedTerm(card.title);
  const correct = option(term, situations[card.title]!);
  const distractors = distractorOffsets.map((offset) => option(term, situations[cards[(index + offset) % cards.length]!.title]!));
  const options = rotate([correct, ...distractors], (index + 1) % 4);

  return {
    id: `medium-${index}`,
    level: 'medium',
    eyebrow: card.title,
    prompt: `Где слово «${term}» использовано правильно?`,
    options,
    correctIndex: options.indexOf(correct),
    explanation: `${card.title}: ${card.text}`,
  };
});

