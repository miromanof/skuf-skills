const rotate = <T,>(items: T[], amount: number) => items.map((_, index) => items[(index + amount) % items.length]!);

const easy = seeds.map<QuizQuestion>((seed, index) => {
  const options = rotate([seed.meaning, ...easyDistractors[seed.term]!], index % 4);
  return { id: `easy-${index}`, level: 'easy', eyebrow: seed.term, prompt: `Что означает «${seed.term}»?`, options, correctIndex: options.indexOf(seed.meaning), explanation: seed.explanation };
});

const medium = seeds.map<QuizQuestion>((seed, index) => {
  const options = rotate([seed.right, ...seed.mediumWrong], (index + 1) % 4);
  return { id: `medium-${index}`, level: 'medium', eyebrow: seed.term, prompt: `Где слово «${seed.term}» использовано правильно?`, options, correctIndex: options.indexOf(seed.right), explanation: seed.explanation };
});

const hard = seeds.map<QuizQuestion>((seed, index) => {
  const options = rotate([seed.term, ...seed.hardWrong], (index + 2) % 4);
  return { id: `hard-${index}`, level: 'hard', eyebrow: 'Контекст', prompt: seed.context, options, correctIndex: options.indexOf(seed.term), explanation: seed.explanation };
});

export const questionBank: Record<QuizLevel, QuizQuestion[]> = { easy, medium, hard };

export function selectQuestions(level: QuizLevel, count = 10, random: () => number = Math.random): QuizQuestion[] {
  const available = [...questionBank[level]];
  if (available.length < count) throw new Error(`Недостаточно вопросов уровня «${LEVELS[level].label}»`);
  for (let index = available.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(random() * (index + 1));
    [available[index], available[swapIndex]] = [available[swapIndex]!, available[index]!];
  }
  return available.slice(0, count);
}

export function scoreBand(score: number): ScoreBand {
  if (score <= 3) return { label: 'Скуф detected', description: 'Начало положено: разбор ошибок быстро прокачает словарь.' };
  if (score <= 6) return { label: 'Уже не скуф', description: 'Ты уверенно узнаёшь современный язык, но пара ловушек ещё осталась.' };
  if (score <= 8) return { label: 'Почти сигма', description: 'Ты уверенно понимаешь современный язык. Осталось разобрать пару ошибок.' };
  return { label: 'Сигма словаря', description: 'Контекст пойман, термины на месте — уровень редактора мемологии.' };
}

