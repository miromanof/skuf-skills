export function resultCaption(score: number, random: () => number = Math.random): string {
  const captions = score <= 2 ? LOW_SCORE_CAPTIONS.veryLow : score <= 4 ? LOW_SCORE_CAPTIONS.low : score === 5 ? LOW_SCORE_CAPTIONS.halfway : RESULT_CAPTIONS;
  return captions[Math.min(captions.length - 1, Math.floor(random() * captions.length))]!;
}

